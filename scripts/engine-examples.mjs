import { writeFileSync } from 'node:fs';
import { generatePuzzle } from '../web/engine/sudoku-core.js';
import { analyze, lessons } from '../web/engine/coach.js';

// Preserve original givens and the exact candidate state before each teaching move.
const examples = Object.fromEntries(lessons.map(lesson => [lesson.id, []]));
const puzzlePool = { L1: [], L4: [], L5: [] };
const targets = { L1: ['open-singles'], L4: ['hidden-single','naked-single','pointing'], L5: ['naked-pair'] };
const perLesson = 4;
for (const [level, ids] of Object.entries(targets)) {
  for (let seed = 2; seed < 200; seed++) {
    let board;
    try {
      board = generatePuzzle({difficulty: level, seed, maxAttempts: 35});
    } catch {
      continue;
    }
    const puzzle = board.map(n => n ?? 0).join('');
    const path = analyze(puzzle);
    if (path.status !== 'unique' || path.difficulty !== level || !path.logicalComplete) continue;
    const poolTarget = { L1: 'open-singles', L4: 'pointing', L5: 'naked-pair' }[level];
    if (path.steps.some(step => step.technique === poolTarget)) {
      if (puzzlePool[level].length < 6) puzzlePool[level].push(puzzle);
    }
    for (const id of ids) {
      if (examples[id].length >= perLesson) continue;
      const stepIndex = path.steps.findIndex(step => step.technique === id &&
        (id !== 'hidden-single' || step.candidates[step.updates[0].index].length > 1) &&
        step.updates.length <= 4);
      if (stepIndex >= 0) examples[id].push({ ...path.steps[stepIndex], puzzle, stepIndex });
    }
    if (ids.every(id => examples[id].length >= perLesson) && puzzlePool[level].length === 6) break;
  }
}
for (const [id, set] of Object.entries(examples)) {
  if (set.length !== perLesson) throw Error(`Missing examples for ${id}`);
}
writeFileSync(new URL('../web/data/examples.js', import.meta.url),
  '// Generated by scripts/engine-examples.mjs from unique, independently seeded classic puzzles.\n' +
  'export const examples = {\n' + Object.entries(examples).map(([id, set]) =>
    '  ' + JSON.stringify(id) + ': [\n' + set.map(step => '    ' + JSON.stringify(step)).join(',\n') + '\n  ]').join(',\n') +
  '\n};\nexport const puzzlePool = ' + JSON.stringify(puzzlePool, null, 2) + ';\n');
console.log(Object.fromEntries(Object.entries(examples).map(([id,set]) => [id, set.length])));
