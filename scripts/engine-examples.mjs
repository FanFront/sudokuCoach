import { readFileSync, writeFileSync } from 'node:fs';
import { countSolutions, generatePuzzle, getUniqueSolution } from '../web/engine/sudoku-core.js';
import { examples as bundledExamples, puzzlePool as bundledPool } from '../web/data/examples.js';
import { analyze, lessons, practiceLevels } from '../web/engine/coach.js';

// Preserve original givens and the exact candidate state before each teaching move.
const examples = Object.fromEntries(lessons.map(lesson => [lesson.id, []]));
const puzzlePool = Object.fromEntries(Object.keys(practiceLevels).map(level => [level, []]));
const targets = {
  L1: ['open-singles'],
  L4: ['hidden-single', 'naked-single', 'pointing', 'claiming'],
  L5: ['naked-pair'],
  advanced: ['hidden-pair', 'hidden-triple', 'x-wing', 'swordfish', 'skyscraper', 'two-string-kite', 'y-wing']
};
const practiceCounts = Object.fromEntries(lessons.map(lesson => [lesson.id, lesson.practiceCount]));

function digPuzzle(solution, seed) {
  const board = [...solution];
  const cells = board.map((_, index) => index);
  let random = seed;
  for (let i = cells.length - 1; i > 0; i--) {
    random = (Math.imul(random, 1664525) + 1013904223) >>> 0;
    const j = Math.floor(random / 0x100000000 * (i + 1));
    [cells[i], cells[j]] = [cells[j], cells[i]];
  }
  let clues = 81;
  for (const cell of cells) {
    board[cell] = null;
    if (countSolutions(board, 2) !== 1) board[cell] = solution[cell];
    else if (--clues <= 24 + seed % 4) break;
  }
  return board;
}
const advancedPuzzles = JSON.parse(readFileSync(new URL('./advanced-puzzles.json', import.meta.url), 'utf8'));
if (process.argv.includes('--reuse')) {
  for (const [id, items] of Object.entries(bundledExamples)) {
    examples[id] = items.map(({puzzle, stepIndex}) => {
      const step = analyze(puzzle).steps[stepIndex];
      if (step?.technique !== id) throw Error(`Bundled example no longer matches ${id}`);
      return { ...step, puzzle, stepIndex };
    });
  }
  Object.assign(puzzlePool, bundledPool);
}
for (const [level, ids] of process.argv.includes('--reuse') ? [] : Object.entries(targets)) {
  console.log(`Generating ${level}`);
  const advanced = level === 'advanced';
  const poolLevel = advanced ? 'L6' : level;
  const poolTarget = practiceLevels[poolLevel].technique;
  const fullBoards = advanced
    ? Object.values(puzzlePool).flat().map(puzzle => getUniqueSolution([...puzzle].map(digit => +digit || null)))
    : [];
  for (let seed = 2; seed < 900; seed++) {
    let board;
    try {
      board = advanced ? digPuzzle(fullBoards[seed % fullBoards.length], seed)
        : generatePuzzle({difficulty: level, seed, maxAttempts: 8});
    } catch {
      continue;
    }
    const puzzle = board.map(n => n ?? 0).join('');
    const path = analyze(puzzle);
    if (path.status !== 'unique' || !path.logicalComplete) continue;
    const pool = puzzlePool[poolLevel];
    if (pool.length < 6 && (advanced || path.difficulty === poolLevel) && path.steps.some(step => step.technique === poolTarget)) {
      if (!pool.includes(puzzle)) pool.push(puzzle);
    }
    for (const id of ids) {
      if (examples[id].length >= practiceCounts[id] || examples[id].some(example => example.puzzle === puzzle)) continue;
      const stepIndex = path.steps.findIndex(step => step.technique === id &&
        (id !== 'hidden-single' || step.candidates[step.updates[0].index].length > 1) &&
        step.updates.length <= 6);
      if (stepIndex >= 0) examples[id].push({ ...path.steps[stepIndex], puzzle, stepIndex });
    }
    if (ids.every(id => examples[id].length >= practiceCounts[id]) && pool.length === 6) break;

  }
}
for (const [id, fixtures] of Object.entries(advancedPuzzles)) {
  examples[id] = fixtures.map(({puzzle, stepIndex}) => {
    const result = analyze(puzzle);
    const step = result.steps[stepIndex];
    if (result.status !== 'unique' || step?.technique !== id) throw Error(`Advanced example no longer matches ${id}`);
    return { ...step, puzzle, stepIndex };
  });
}
for (const [level, pool] of Object.entries(puzzlePool)) {
  if (pool.length !== 6) throw Error(`Missing fallback puzzles for ${level}`);
}
for (const [id, set] of Object.entries(examples)) {
  if (set.length !== practiceCounts[id]) throw Error(`Missing examples for ${id}`);
}
writeFileSync(new URL('../web/data/examples.js', import.meta.url),
  '// Generated by scripts/engine-examples.mjs from unique, independently seeded classic puzzles.\n' +
  'export const examples = {\n' + Object.entries(examples).map(([id, set]) =>
    '  ' + JSON.stringify(id) + ': [\n' + set.map(step => '    ' + JSON.stringify(step)).join(',\n') + '\n  ]').join(',\n') +
  '\n};\nexport const puzzlePool = ' + JSON.stringify(puzzlePool, null, 2) + ';\n');
console.log(Object.fromEntries(Object.entries(examples).map(([id,set]) => [id, set.length])));
